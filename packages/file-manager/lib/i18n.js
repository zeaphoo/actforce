/**
 * Detect the best supported language from navigator.language.
 * zh-HK / zh-TW / vi get their own locale; other Chinese variants
 * fall back to zh-CN; everything else falls back to en.
 */
function detectLanguage() {
  if (typeof navigator === 'undefined') return 'en';
  const lang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
  if (lang.startsWith('zh')) {
    if (lang.includes('hk')) return 'zh-HK';
    if (lang.includes('tw') || lang.includes('hant')) return 'zh-TW';
    return 'zh-CN';
  }
  if (lang.startsWith('vi')) return 'vi';
  return 'en';
}

i18n.use(initReactI18next).init({
  resources,
  lng: detectLanguage(),
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
  defaultNS: 'translation',
});

export default i18n;
